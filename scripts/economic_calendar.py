"""EXP-FX000005 改善ループ第3試行: 経済指標カレンダー(BOJ・FOMC会合)による
新規エントリーのブラックアウト窓.

背景: 司令塔の依頼で連敗パターンを分析した結果、Train/Validation/Testそれぞれの
最大連敗が特定の日に集中し、うち2件(Train 2024-04-26・Test 2026-07-30〜31)は
BOJ金融政策決定会合の当日、1件(Validation 2025-06-13)はイスラエルによる
イラン攻撃という予測不能な地政学ショックだったとWebSearchで確認した(司令塔
確認済み)。本モジュールはBOJ・FOMCという**事前に日程が公表されている**会合を
対象にブラックアウト窓を設ける。地政学ショックのような予定外イベントは
原理的にカレンダーでは防げない(この限界は正直に明記する)。

会合日程はすべてWebSearchで検証済み(出典: 日本銀行公式サイト boj.or.jp、
Federal Reserve公式サイト federalreserve.gov 等)。対象通貨は全てJPY建て
(USD/JPY・EUR/JPY・GBP/JPY・AUD/JPY)のため、BOJ会合は直接的要因、FOMC会合は
円全体に影響するリスクセンチメント/ドル全体の動きを通じた間接的要因として、
いずれも全4通貨に適用する。

事前登録(結果を見る前に固定): ブラックアウト窓は各会合の[開催初日 00:00 JST,
開催最終日 24:00 JST]の前後に24時間のバッファを追加した
[初日-24h, 最終日+24h]とする。FOMCは米国東部時間で日付が公表されるため、
JST換算では発表が最終日の翌日未明(2:00pm ET ≈ 深夜3-4時JST)にずれるが、
本ブラックアウト窓は米国日付をそのままJST日付として扱う簡略化を行っており、
そのズレは24時間のバッファで吸収する設計とする。
"""

